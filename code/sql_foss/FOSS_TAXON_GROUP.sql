-- Create View GAP_PRODUCTS.FOSS_TAXON_GROUP
--
-- Queries hierarchial taxonomic information for each GROUP_CODE in 
-- GAP_TAXONOMY.TAXON_GROUP_STANZAS. 
--
-- Contributors: Ned Laman (ned.laman@noaa.gov), 
--               Zack Oyafuso (zack.oyafuso@noaa.gov), 
--               Emily Markowitz (emily.markowitz@noaa.gov)
--

CREATE VIEW GAP_PRODUCTS.FOSS_TAXON_GROUP AS
SELECT
    REPLACE(REPLACE(RANK_ID, '_TAXON', ''), 'SPECIES_NAME', 'SPECIES') AS RANK_ID,
    CLASSIFICATION,
    SPECIES_CODE
FROM (
    SELECT DISTINCT
        SPECIES_CODE,
        SPECIES_NAME,
        GENUS_TAXON,
        SUBFAMILY_TAXON,
        FAMILY_TAXON,
        ORDER_TAXON,
        CLASS_TAXON,
        PHYLUM_TAXON,
        KINGDOM_TAXON
    FROM
        GAP_TAXONOMY.TAXON_GROUP_COMPOSITION
        JOIN GAP_TAXONOMY.TAXON_GROUP_STANZAS USING (GROUP_STANZA_ID)
        JOIN GAP_TAXONOMY.TAXONOMIC_CLASSIFICATION USING (SPECIES_CODE)
    WHERE
        SPECIES_CODE = GROUP_CODE
        AND ACTIVE = 1
) tt
UNPIVOT (
    CLASSIFICATION FOR RANK_ID IN (
        SPECIES_NAME,
        GENUS_TAXON,
        SUBFAMILY_TAXON,
        FAMILY_TAXON,
        ORDER_TAXON,
        CLASS_TAXON,
        PHYLUM_TAXON,
        KINGDOM_TAXON
    )
)
WHERE
    CLASSIFICATION IS NOT NULL
ORDER BY
    SPECIES_CODE,
    RANK_ID,
    CLASSIFICATION 
;

GRANT SELECT ON GAP_PRODUCTS.FOSS_TAXON_GROUP TO PUBLIC;
