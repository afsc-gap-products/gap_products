-- Mirror of GAP_PRODUCTS.TAXON_GROUPS
WITH LATEST_CHG AS (
    SELECT 
        OLD_SPECIES_CODE,
        NEW_SPECIES_CODE,
        ROW_NUMBER() OVER (
            PARTITION BY OLD_SPECIES_CODE 
            ORDER BY YEAR_CHANGED DESC
        ) AS rn
    FROM 
        GAP_TAXONOMY.TAXONOMIC_CHANGES
)
SELECT 
    STANZAS.GROUP_CODE,
    COMPS.SPECIES_CODE AS SPECIES_CODE,
    TAX_INFO.SPECIES_NAME,
    TAX_INFO.COMMON_NAME,
    TAX_INFO.ID_RANK,
    TAX_INFO.DATABASE,
    TAX_INFO.DATABASE_ID,
    TAX_INFO.GENUS_TAXON,
    TAX_INFO.SUBFAMILY_TAXON,
    TAX_INFO.FAMILY_TAXON,
    TAX_INFO.SUPERFAMILY_TAXON,
    TAX_INFO.INFRAORDER_TAXON,
    TAX_INFO.SUBORDER_TAXON,
    TAX_INFO.ORDER_TAXON,
    TAX_INFO.SUPERORDER_TAXON,
    TAX_INFO.INFRACLASS_TAXON,
    TAX_INFO.SUBCLASS_TAXON,
    TAX_INFO.CLASS_TAXON,
    TAX_INFO.SUPERCLASS_TAXON,
    TAX_INFO.SUBPHYLUM_TAXON,
    TAX_INFO.PHYLUM_TAXON,
    TAX_INFO.KINGDOM_TAXON,
    
    TRUNC(SYSDATE) AKFIN_LOAD_DATE
FROM 
    GAP_TAXONOMY.TAXON_GROUP_STANZAS STANZAS
JOIN 
    GAP_TAXONOMY.TAXON_GROUP_COMPOSITION COMPS 
        ON COMPS.GROUP_STANZA_ID = STANZAS.GROUP_STANZA_ID
-- Join only the latest change record per OLD_SPECIES_CODE
LEFT JOIN 
    LATEST_CHG CHG 
        ON CHG.OLD_SPECIES_CODE = COMPS.SPECIES_CODE
        AND CHG.rn = 1
JOIN 
    GAP_TAXONOMY.TAXONOMIC_CLASSIFICATION TAX_INFO 
        ON TAX_INFO.SPECIES_CODE = COALESCE(CHG.NEW_SPECIES_CODE, COMPS.SPECIES_CODE)
WHERE 
    STANZAS.YEAR_END = (SELECT MAX(YEAR_END) FROM GAP_TAXONOMY.TAXON_GROUP_STANZAS)
    AND TAX_INFO.ACTIVE = 1
ORDER BY 
    STANZAS.GROUP_CODE
;
