-- CREATE CTD_VARIABLE_CODES

CREATE TABLE VARIABLE_CODES (
  VARIABLE    NUMBER(3,0) NOT NULL,
  NAME        VARCHAR2(255 BYTE),
  UNITS       VARCHAR2(255 BYTE),
  DESCRIPTION VARCHAR2(255 BYTE),
  
  CONSTRAINT pk_variable_codes
    PRIMARY KEY (VARIABLE)  
);
GRANT SELECT ON VARIABLE_CODES TO PUBLIC;


CREATE TABLE DIRECTION_CODES (
  DIRECTION   NUMBER(1,0) NOT NULL,
  DESCRIPTION VARCHAR2(255 BYTE),
  
  CONSTRAINT pk_direction_codes
    PRIMARY KEY (DIRECTION)
);
GRANT SELECT ON DIRECTION_CODES TO PUBLIC;

CREATE TABLE INSTRUMENT_CODES (
  INSTRUMENT  NUMBER(3,0) NOT NULL,
  DESCRIPTION VARCHAR2(255 BYTE),
  
  CONSTRAINT pk_instrument_codes 
    PRIMARY KEY (INSTRUMENT)
);
GRANT SELECT ON INSTRUMENT_CODES TO PUBLIC;

