CREATE TABLE ENVIRONMENTAL (
  HAULJOIN   NUMBER(12,0)  NOT NULL, 
  INSTRUMENT NUMBER(3,0)   NOT NULL,
  DIRECTION  NUMBER(12,0)  NOT NULL,
  DEPTH_M    NUMBER(5,0)   NOT NULL,
  VARIABLE   NUMBER(3,0)   NOT NULL,
  VALUE      NUMBER(11,6)  NOT NULL, 
  
  -- Foreign Key Constraints
  --CONSTRAINT fk_env_hauljoin 
    --FOREIGN KEY (HAULJOIN) REFERENCES RACEBASE.HAUL(HAULJOIN), 
    
    CONSTRAINT fk_env_instrument 
    FOREIGN KEY (INSTRUMENT) REFERENCES INSTRUMENT_CODES(INSTRUMENT),
    
  CONSTRAINT fk_env_direction 
    FOREIGN KEY (DIRECTION) REFERENCES DIRECTION_CODES(DIRECTION),
    
  CONSTRAINT fk_env_variable 
    FOREIGN KEY (VARIABLE) REFERENCES VARIABLE_CODES(VARIABLE),
    
  -- Composite Primary Key Constraint
  CONSTRAINT pk_env_data 
    PRIMARY KEY (HAULJOIN, DIRECTION, DEPTH_M, VARIABLE)
);
GRANT SELECT ON ENVIRONMENTAL TO PUBLIC;







